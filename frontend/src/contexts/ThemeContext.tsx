import React, { createContext, useContext, useEffect, useState } from 'react';

type Theme = 'light' | 'dark';

interface ThemeContextType {
  theme: Theme;
  toggleTheme: () => void;
}

const ThemeContext = createContext<ThemeContextType | undefined>(undefined);

export const ThemeProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [theme, setTheme] = useState<Theme>(() => {
    const savedTheme = localStorage.getItem('theme');
    if (savedTheme === 'light' || savedTheme === 'dark') {
      return savedTheme;
    }
    // Default to light as Figma design doesn't officially support dark, we added it on top
    return 'light';
  });

  useEffect(() => {
    localStorage.setItem('theme', theme);
    
    // Disable all CSS transitions temporarily to prevent intermediate colors (gray flash)
    document.documentElement.classList.add('disable-transitions');
    
    if (theme === 'dark') {
      document.documentElement.setAttribute('data-theme', 'dark');
    } else {
      document.documentElement.removeAttribute('data-theme');
    }

    // Force a reflow to ensure the new colors apply instantly without transition
    window.getComputedStyle(document.documentElement).getPropertyValue('opacity');
    
    // Re-enable transitions in the next frame
    setTimeout(() => {
      document.documentElement.classList.remove('disable-transitions');
    }, 0);
  }, [theme]);

  const toggleTheme = () => {
    setTheme(prev => (prev === 'light' ? 'dark' : 'light'));
  };

  return (
    <ThemeContext.Provider value={{ theme, toggleTheme }}>
      {children}
    </ThemeContext.Provider>
  );
};

export const useTheme = () => {
  const context = useContext(ThemeContext);
  if (context === undefined) {
    throw new Error('useTheme must be used within a ThemeProvider');
  }
  return context;
};
